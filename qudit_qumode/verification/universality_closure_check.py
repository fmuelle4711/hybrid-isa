"""
universality_closure_check.py -- numerical check of Sec V's universality claim.

ADDITIVE ONLY.  Does not modify any existing file.

Question: does the Lie algebra generated by
    {X_ij, Z_l}                     (su(d) on qudit, tensor Id on modes)
  + {sigma_z^(01) tensor x, sigma_z^(01) tensor p}   (conditional displacement)
  + {i (a1 a2^dag - a1^dag a2)}     (beam splitter, two-mode only)
contain operators of polynomial degree >= 3 in the mode quadratures?

Approach:
  - Represent operators as dense complex matrices on the truncated
    (d * N)-dim (single mode) or (d * N1 * N2)-dim (two-mode) Hilbert space.
  - Iterate: at each round, take commutators of all pairs involving at
    least one "new" element from last round; orthogonalise (Gram-Schmidt
    on flattened matrices) with explicit tolerance; add any new
    linearly-independent element.  Stop when no new element or a hard
    dim cap is reached.
  - Report iteration-by-iteration span dimension and max polynomial
    degree (= matrix bandwidth of the (m, n) index within a stated
    "safe interior" window of Fock indices).
  - Repeat at multiple Fock cutoffs to check N-independence.
  - Control test with UNCONDITIONAL displacement (I tensor x, I tensor p)
    should stay Gaussian (max degree 1).
"""

from __future__ import annotations

import csv
import os
import sys
import time

import numpy as np


# =====================================================================
# Fock and qudit operator builders
# =====================================================================

def fock_ops(N: int):
    """Truncated a, a^dag, x, p on N-dim Fock space."""
    a = np.diag(np.sqrt(np.arange(1, N, dtype=float)), 1).astype(complex)
    ad = a.conj().T
    x = a + ad
    p = 1j * (ad - a)
    return a, ad, x, p


def qudit_seeds(d: int):
    """Paper's QT + QPS generators: X_ij (Hermitian off-diag) and Z_l (diag proj)."""
    ops = []
    for i in range(d):
        for j in range(i+1, d):
            E = np.zeros((d, d), dtype=complex)
            E[i, j] = 1.0; E[j, i] = 1.0
            ops.append(E)
    for l in range(d):
        E = np.zeros((d, d), dtype=complex)
        E[l, l] = 1.0
        ops.append(E)
    return ops


def sigma_z_01(d: int):
    """|0><0| - |1><1| embedded in the d-dim qudit space."""
    sz = np.zeros((d, d), dtype=complex)
    sz[0, 0] = 1.0
    sz[1, 1] = -1.0
    return sz


# =====================================================================
# Seed builders for each scenario
# =====================================================================

def build_seeds_hybrid_1mode(d: int, N: int):
    """su(d) generators tensor I  +  sigma_z^(01) tensor x  +  sigma_z^(01) tensor p."""
    Qs = qudit_seeds(d)
    I_mode = np.eye(N, dtype=complex)
    _, _, x, p = fock_ops(N)
    sz01 = sigma_z_01(d)
    seeds = [np.kron(Q, I_mode) for Q in Qs]
    seeds.append(np.kron(sz01, x))
    seeds.append(np.kron(sz01, p))
    return seeds


def build_seeds_control_1mode(d: int, N: int):
    """Control: su(d) generators  +  UNCONDITIONAL I tensor x, I tensor p."""
    Qs = qudit_seeds(d)
    I_mode = np.eye(N, dtype=complex)
    I_qudit = np.eye(d, dtype=complex)
    _, _, x, p = fock_ops(N)
    seeds = [np.kron(Q, I_mode) for Q in Qs]
    seeds.append(np.kron(I_qudit, x))
    seeds.append(np.kron(I_qudit, p))
    return seeds


def build_seeds_hybrid_2mode(d: int, N: int):
    """su(d) tensor I_2  +  sigma_z^(01) tensor x_1, p_1, x_2, p_2  +  I_qudit tensor BS."""
    Qs = qudit_seeds(d)
    I_mode = np.eye(N, dtype=complex)
    I_qudit = np.eye(d, dtype=complex)
    I_2 = np.kron(I_mode, I_mode)
    a, ad, x, p = fock_ops(N)
    sz01 = sigma_z_01(d)

    x1 = np.kron(x, I_mode); p1 = np.kron(p, I_mode)
    x2 = np.kron(I_mode, x); p2 = np.kron(I_mode, p)

    a1 = np.kron(a, I_mode); ad1 = np.kron(ad, I_mode)
    a2 = np.kron(I_mode, a); ad2 = np.kron(I_mode, ad)
    BS = 1j * (a1 @ ad2 - ad1 @ a2)

    seeds = [np.kron(Q, I_2) for Q in Qs]
    seeds.append(np.kron(sz01, x1))
    seeds.append(np.kron(sz01, p1))
    seeds.append(np.kron(sz01, x2))
    seeds.append(np.kron(sz01, p2))
    seeds.append(np.kron(I_qudit, BS))
    return seeds


# =====================================================================
# Lie closure computation (queue-based, SVD/GS orthogonalisation)
# =====================================================================

def compute_lie_closure(seeds, tol: float, max_iter: int, hard_dim_cap: int, verbose=True):
    """
    Return (basis_matrices, iter_bounds, dims_per_iter).

    iter_bounds[k] = (start_idx, end_idx) marking which basis elements
    were added at iteration k (iter 0 = seeds).
    """
    # Seed orthonormalisation via Gram-Schmidt on flattened matrices
    basis_mats = []
    basis_flat = []

    def try_add(M):
        f = M.reshape(-1).astype(complex).copy()
        for b in basis_flat:
            f -= np.vdot(b, f) * b
        nrm = float(np.linalg.norm(f))
        if nrm > tol:
            basis_flat.append(f / nrm)
            basis_mats.append(M.copy())
            return True
        return False

    for s in seeds:
        try_add(s)

    iter_bounds = [(0, len(basis_mats))]
    dims_per_iter = [len(basis_mats)]

    prev_end = 0
    curr_end = len(basis_mats)

    for it in range(max_iter):
        new_start = curr_end
        # New elements: indices [prev_end, curr_end)
        # Old elements: indices [0, prev_end)
        # Pairs to consider: (i, j), i < j, with at least one of i, j in [prev_end, curr_end)
        added_this_iter = 0
        pairs_this_iter = 0

        # new × new
        for i in range(prev_end, curr_end):
            for j in range(i + 1, curr_end):
                pairs_this_iter += 1
                Ci = basis_mats[i]; Cj = basis_mats[j]
                C = Ci @ Cj - Cj @ Ci
                # cheap early-out
                if np.max(np.abs(C)) < tol:
                    continue
                if try_add(C):
                    added_this_iter += 1
                    if len(basis_mats) >= hard_dim_cap:
                        break
            if len(basis_mats) >= hard_dim_cap:
                break

        # new × old
        if len(basis_mats) < hard_dim_cap:
            for i in range(prev_end, curr_end):
                for j in range(0, prev_end):
                    pairs_this_iter += 1
                    Ci = basis_mats[i]; Cj = basis_mats[j]
                    C = Ci @ Cj - Cj @ Ci
                    if np.max(np.abs(C)) < tol:
                        continue
                    if try_add(C):
                        added_this_iter += 1
                        if len(basis_mats) >= hard_dim_cap:
                            break
                if len(basis_mats) >= hard_dim_cap:
                    break

        prev_end = curr_end
        curr_end = len(basis_mats)
        iter_bounds.append((new_start, curr_end))
        dims_per_iter.append(curr_end)

        if verbose:
            print(f"  iter {it+1}: dim = {curr_end:5d}   added = {added_this_iter:5d}   pairs = {pairs_this_iter}")

        if added_this_iter == 0 or curr_end >= hard_dim_cap:
            break

    return basis_mats, iter_bounds, dims_per_iter


# =====================================================================
# Polynomial-degree extraction (matrix bandwidth in safe interior)
# =====================================================================

def max_bandwidth_1mode(op, d: int, N: int, safe_max: int, tol: float):
    """
    op has shape (d*N, d*N).  Reshape as (d, N, d, N), examine only Fock indices
    m, n in [0, safe_max].  Return max |m - n| for which any qudit-blocked
    matrix element |op[i, m, j, n]| exceeds tol.
    """
    R = op.reshape(d, N, d, N)
    sub = R[:, :safe_max+1, :, :safe_max+1]     # (d, S, d, S)
    absm = np.abs(sub)
    # bandwidth per (m, n) pair (collapsed over qudit indices)
    per_mn = absm.max(axis=(0, 2))               # shape (S, S)
    S = safe_max + 1
    max_bw = 0
    for m in range(S):
        for n in range(S):
            if per_mn[m, n] > tol:
                if abs(m - n) > max_bw:
                    max_bw = abs(m - n)
    return max_bw


def max_bandwidth_2mode(op, d: int, N: int, safe_max: int, tol: float):
    """
    Two-mode version.  Reshape as (d, N, N, d, N, N).  Report separate
    bandwidths in each mode, plus a JOINT indicator (True iff there exists
    a matrix element with |m1-n1| >= 1 AND |m2-n2| >= 1).
    """
    R = op.reshape(d, N, N, d, N, N)
    S = safe_max + 1
    sub = R[:, :S, :S, :, :S, :S]                # (d, S, S, d, S, S)
    absm = np.abs(sub)
    # collapse qudit indices for bandwidth: per_(m1,m2,n1,n2)
    per = absm.max(axis=(0, 3))                  # (S, S, S, S)
    max_bw1 = 0
    max_bw2 = 0
    joint_deg = 0
    for m1 in range(S):
        for m2 in range(S):
            for n1 in range(S):
                for n2 in range(S):
                    if per[m1, m2, n1, n2] > tol:
                        b1 = abs(m1 - n1); b2 = abs(m2 - n2)
                        if b1 > max_bw1: max_bw1 = b1
                        if b2 > max_bw2: max_bw2 = b2
                        if b1 >= 1 and b2 >= 1:
                            if b1 + b2 > joint_deg:
                                joint_deg = b1 + b2
    return max_bw1, max_bw2, joint_deg


def basis_max_degree_1mode(basis, d, N, safe_max, tol):
    max_deg = 0
    per_op = []
    for M in basis:
        bw = max_bandwidth_1mode(M, d, N, safe_max, tol)
        per_op.append(bw)
        if bw > max_deg:
            max_deg = bw
    return max_deg, per_op


def basis_max_degree_2mode(basis, d, N, safe_max, tol):
    max_bw1 = 0; max_bw2 = 0; max_joint = 0
    per_op = []
    for M in basis:
        bw1, bw2, jt = max_bandwidth_2mode(M, d, N, safe_max, tol)
        per_op.append((bw1, bw2, jt))
        if bw1 > max_bw1: max_bw1 = bw1
        if bw2 > max_bw2: max_bw2 = bw2
        if jt > max_joint: max_joint = jt
    return max_bw1, max_bw2, max_joint, per_op


# =====================================================================
# Runners
# =====================================================================

def run_single_mode(scenario_name, seed_builder, d, N, tol, max_iter, hard_dim_cap, log, safe_max=None):
    """
    Compute Lie closure and report per-iteration max polynomial degree in a
    stated "safe interior" window.

    IMPORTANT (truncation-ghost handling): commutators of [x, p] on truncated
    Fock produce a spurious `-2iN |N-1><N-1|` term.  Its support is at
    (m, n) = (N-1, N-1).  Each subsequent commutation with x or p can shift
    the support by at most 1 in either index.  So after k commutations from
    the seeds, boundary-generated ops can have support in the safe subgrid
    (m, n) in [0, safe_max]^2 only if k >= 2*(N-1-safe_max).  We choose
    safe_max and max_iter so that the reported per-iteration max degree is
    NOT contaminated by boundary leak, and report the boundary-leak
    threshold explicitly.
    """
    if safe_max is None:
        safe_max = max(1, N // 2 - 1)
    boundary_leak_iter = 2 * (N - 1 - safe_max)
    log(f"\n== {scenario_name}   d={d}  N={N}  tol={tol:.1e}  max_iter={max_iter} ==")
    log(f"  safe_max = {safe_max} (Fock index window [0, {safe_max}])")
    log(f"  boundary-leak threshold: iter >= {boundary_leak_iter}"
        f"  (results at earlier iters are truncation-ghost-free)")
    seeds = seed_builder(d, N)
    dim_full = d * N
    log(f"  seeds = {len(seeds)}   ambient dim = {dim_full}   u(dN) dim = {dim_full * dim_full}")

    t0 = time.time()
    basis, iter_bounds, dims = compute_lie_closure(
        seeds, tol=tol, max_iter=max_iter, hard_dim_cap=hard_dim_cap, verbose=False,
    )
    elapsed = time.time() - t0
    per_iter_deg_added = []
    per_iter_deg_cumul = []
    running_max = 0
    for k, (s, e) in enumerate(iter_bounds):
        if s == e:
            per_iter_deg_added.append(None)
            per_iter_deg_cumul.append(running_max)
            continue
        maxd = 0
        for M in basis[s:e]:
            bw = max_bandwidth_1mode(M, d, N, safe_max, tol)
            if bw > maxd:
                maxd = bw
        per_iter_deg_added.append(maxd)
        if maxd > running_max:
            running_max = maxd
        per_iter_deg_cumul.append(running_max)

    final_max_deg = per_iter_deg_cumul[-1]

    log(f"  elapsed {elapsed:.1f}s   final dim = {dims[-1]}")
    log(f"  iteration table:")
    log(f"    iter | dim  | max deg of ops ADDED this iter | cumulative max deg | boundary-safe?")
    for k, ((s, e), deg_added, deg_cum) in enumerate(zip(iter_bounds, per_iter_deg_added, per_iter_deg_cumul)):
        safe_flag = "yes" if k < boundary_leak_iter else "NO (boundary leak possible)"
        log(f"    {k:4d} | {e:4d} | {str(deg_added):>3}                             | {deg_cum} | {safe_flag}")
    log(f"  MAX POLY DEGREE (safe_max={safe_max}) at last boundary-safe iter = "
        f"{per_iter_deg_cumul[min(boundary_leak_iter-1, len(per_iter_deg_cumul)-1)]}")

    return dict(
        scenario=scenario_name, d=d, N=N, tol=tol,
        n_seeds=len(seeds),
        dims_per_iter=dims,
        iter_bounds=iter_bounds,
        per_iter_max_deg_added=per_iter_deg_added,
        per_iter_max_deg_cumul=per_iter_deg_cumul,
        final_dim=dims[-1],
        final_max_deg=final_max_deg,
        max_deg_boundary_safe=per_iter_deg_cumul[min(boundary_leak_iter-1, len(per_iter_deg_cumul)-1)],
        elapsed_s=elapsed,
        safe_max=safe_max,
        boundary_leak_iter=boundary_leak_iter,
    )


def run_two_mode(scenario_name, seed_builder, d, N, tol, max_iter, hard_dim_cap, log, safe_max=None):
    if safe_max is None:
        safe_max = max(1, N // 2 - 1)
    boundary_leak_iter = 2 * (N - 1 - safe_max)
    log(f"\n== {scenario_name}   d={d}  N={N} (per mode)  tol={tol:.1e}  max_iter={max_iter} ==")
    log(f"  safe_max = {safe_max}   boundary-leak threshold: iter >= {boundary_leak_iter}")
    seeds = seed_builder(d, N)
    dim_full = d * N * N
    log(f"  seeds = {len(seeds)}   ambient dim = {dim_full}   u(d*N*N) dim = {dim_full * dim_full}")

    t0 = time.time()
    basis, iter_bounds, dims = compute_lie_closure(
        seeds, tol=tol, max_iter=max_iter, hard_dim_cap=hard_dim_cap, verbose=False,
    )
    elapsed = time.time() - t0

    # Compute per-iteration cumulative single-mode bandwidths + joint deg
    per_iter_bw1 = []
    per_iter_bw2 = []
    per_iter_joint = []
    r_max1 = 0; r_max2 = 0; r_maxj = 0
    for k, (s, e) in enumerate(iter_bounds):
        if s == e:
            per_iter_bw1.append(r_max1); per_iter_bw2.append(r_max2); per_iter_joint.append(r_maxj)
            continue
        bwa = 0; bwb = 0; jt = 0
        for M in basis[s:e]:
            b1, b2, j = max_bandwidth_2mode(M, d, N, safe_max, tol)
            if b1 > bwa: bwa = b1
            if b2 > bwb: bwb = b2
            if j > jt: jt = j
        r_max1 = max(r_max1, bwa); r_max2 = max(r_max2, bwb); r_maxj = max(r_maxj, jt)
        per_iter_bw1.append(r_max1); per_iter_bw2.append(r_max2); per_iter_joint.append(r_maxj)

    log(f"  elapsed {elapsed:.1f}s   final dim = {dims[-1]}")
    log(f"  iteration table (cumulative):")
    log(f"    iter | dim  | max bw mode1 | max bw mode2 | max joint deg | boundary-safe?")
    for k, ((s, e), b1, b2, jt) in enumerate(zip(iter_bounds, per_iter_bw1, per_iter_bw2, per_iter_joint)):
        safe_flag = "yes" if k < boundary_leak_iter else "NO"
        log(f"    {k:4d} | {e:4d} | {b1:12d} | {b2:12d} | {jt:13d} | {safe_flag}")
    safe_idx = min(boundary_leak_iter-1, len(iter_bounds)-1)

    return dict(
        scenario=scenario_name, d=d, N=N, tol=tol,
        n_seeds=len(seeds),
        dims_per_iter=dims,
        iter_bounds=iter_bounds,
        per_iter_bw1=per_iter_bw1, per_iter_bw2=per_iter_bw2, per_iter_joint=per_iter_joint,
        final_dim=dims[-1],
        max_bw1_safe=per_iter_bw1[safe_idx],
        max_bw2_safe=per_iter_bw2[safe_idx],
        max_joint_safe=per_iter_joint[safe_idx],
        elapsed_s=elapsed,
        safe_max=safe_max,
        boundary_leak_iter=boundary_leak_iter,
    )


# =====================================================================
# Main driver
# =====================================================================

def main():
    outdir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          'results')
    os.makedirs(outdir, exist_ok=True)
    logpath = os.path.join(outdir, 'universality_closure_check.log')
    csvpath = os.path.join(outdir, 'universality_closure_check.csv')

    fh = open(logpath, 'w')
    def log(msg):
        print(msg); fh.write(msg + '\n'); fh.flush()

    log("=" * 78)
    log("Universality closure check -- Sec V of the paper")
    log("=" * 78)

    all_results = []
    tol = 1e-9

    # ------------------------------------------------------------
    # Design of the test to be robust against truncation ghosts:
    #
    #   To DETECT bandwidth D, we must look at Fock indices m, n with
    #   |m - n| = D somewhere in the window [0, safe_max]. So safe_max
    #   must be >= D. To detect degree >= 3 in the closure we set
    #       safe_max = 3
    #   (bandwidth 0/1/2/3 all detectable within this window).
    #
    #   Truncation ghosts appear from [I⊗x, I⊗p] = 2i I - 2i N |N-1><N-1|
    #   at iter 1. Each further commutation with x or p can shift the
    #   ghost support by at most 1 Fock index per side. So after k
    #   commutations from the ghost's iter-1 origin, ghost support can
    #   reach (N-1-a, N-1-b) with a+b <= k. For that to intersect the
    #   safe window [0, safe_max]^2 we need
    #       a+b >= 2 (N-1 - safe_max)
    #   i.e., iter >= 1 + 2 (N-1 - safe_max).
    #
    #   With safe_max = 3:  safe iter range is [1, 2 N - 6].
    #     N =  6:  iters 1..6      safe.  (Hybrid closure hits u(dN)=576 by iter 4 anyway.)
    #     N =  8:  iters 1..10     safe.
    #     N = 10:  iters 1..14     safe.
    #
    # We ALWAYS use safe_max = 3 for degree detection.  We cap max_iter
    # below the boundary-safe threshold so the CONTROL test is trustworthy.
    # ------------------------------------------------------------

    SAFE_MAX = 3

    # --- Step 1: single-mode HYBRID at multiple N (main check) ---
    for N, max_iter in [(6, 4), (8, 5), (10, 5)]:
        cap = 4 * N * 4 * N   # allow reaching full u(dN)
        r = run_single_mode("HYBRID_1MODE", build_seeds_hybrid_1mode,
                            d=4, N=N, tol=tol, max_iter=max_iter,
                            hard_dim_cap=cap, log=log, safe_max=SAFE_MAX)
        all_results.append(r)

    # --- Step 3: single-mode CONTROL (unconditional displacement) ---
    # Prediction: max deg stays at 1 for all boundary-safe iterations.
    # We match max_iter to the hybrid.
    for N, max_iter in [(6, 4), (8, 5), (10, 5)]:
        cap = 4 * N * 4 * N
        r = run_single_mode("CONTROL_1MODE_UNCOND_DISPL", build_seeds_control_1mode,
                            d=4, N=N, tol=tol, max_iter=max_iter,
                            hard_dim_cap=cap, log=log, safe_max=SAFE_MAX)
        all_results.append(r)

    # --- Step 2: two-mode HYBRID with BS ---
    # For safe_max=2, boundary threshold is 2*(N-1-2) = 2N-6.  With N=4
    # this is 2, meaning iters 0..1 are safe -- ONLY THE SEEDS.  So use
    # safe_max=1 and N=4: threshold = 4, iters 0..3 safe.  This lets us
    # detect bandwidth on each mode up to 1 and joint deg up to 2, which
    # is enough to show joint support (both modes touched in a single
    # matrix element).  For genuine non-Gaussian at joint level we'd
    # need larger N; the single-mode result already resolves the
    # non-Gaussian claim, so here we just verify joint support.
    SAFE_MAX_2M = 1
    for N, max_iter in [(4, 3)]:
        cap = 4 * N * N * 4 * N * N
        r = run_two_mode("HYBRID_2MODE_WITH_BS", build_seeds_hybrid_2mode,
                         d=4, N=N, tol=tol, max_iter=max_iter,
                         hard_dim_cap=cap, log=log, safe_max=SAFE_MAX_2M)
        all_results.append(r)

    # --- Two-mode CONTROL (unconditional displacements + BS) ---
    # Sanity check that BS alone doesn't produce non-Gaussian.
    def build_seeds_control_2mode(d, N):
        Qs = qudit_seeds(d)
        I_mode = np.eye(N, dtype=complex)
        I_qudit = np.eye(d, dtype=complex)
        I_2 = np.kron(I_mode, I_mode)
        a, ad, x, p = fock_ops(N)
        x1 = np.kron(x, I_mode); p1 = np.kron(p, I_mode)
        x2 = np.kron(I_mode, x); p2 = np.kron(I_mode, p)
        a1 = np.kron(a, I_mode); ad1 = np.kron(ad, I_mode)
        a2 = np.kron(I_mode, a); ad2 = np.kron(I_mode, ad)
        BS = 1j * (a1 @ ad2 - ad1 @ a2)
        seeds = [np.kron(Q, I_2) for Q in Qs]
        seeds.append(np.kron(I_qudit, x1))
        seeds.append(np.kron(I_qudit, p1))
        seeds.append(np.kron(I_qudit, x2))
        seeds.append(np.kron(I_qudit, p2))
        seeds.append(np.kron(I_qudit, BS))
        return seeds

    for N, max_iter in [(4, 3)]:
        cap = 4 * N * N * 4 * N * N
        r = run_two_mode("CONTROL_2MODE_UNCOND_DISPL_WITH_BS", build_seeds_control_2mode,
                         d=4, N=N, tol=tol, max_iter=max_iter,
                         hard_dim_cap=cap, log=log, safe_max=SAFE_MAX_2M)
        all_results.append(r)

    # --- CSV summary ---
    fields = ['scenario', 'd', 'N', 'tol', 'n_seeds', 'final_dim',
              'final_max_deg', 'max_bw1', 'max_bw2', 'max_joint',
              'elapsed_s', 'safe_max']
    with open(csvpath, 'w', newline='') as fcsv:
        w = csv.DictWriter(fcsv, fieldnames=fields, extrasaction='ignore')
        w.writeheader()
        for r in all_results:
            row = {k: r.get(k) for k in fields}
            w.writerow(row)

    log(f"\nCSV saved: {csvpath}")
    log(f"Log saved: {logpath}")
    fh.close()


if __name__ == '__main__':
    main()
